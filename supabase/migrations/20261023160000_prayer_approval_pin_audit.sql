CREATE TABLE IF NOT EXISTS public.pedidos_oracao_pins (
  usuario_id uuid PRIMARY KEY REFERENCES public.usuarios(id) ON DELETE CASCADE,
  igreja_id uuid NOT NULL REFERENCES public.igrejas(id) ON DELETE CASCADE,
  pin_salt text NOT NULL CHECK (pin_salt ~ '^[0-9a-f]{32}$'),
  pin_hash text NOT NULL CHECK (pin_hash ~ '^[0-9a-f]{128}$'),
  tentativas_falhas integer NOT NULL DEFAULT 0 CHECK (tentativas_falhas >= 0),
  bloqueado_ate timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (usuario_id, igreja_id)
);

ALTER TABLE public.pedidos_oracao_pins ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.pedidos_oracao_pins FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.pedidos_oracao_pins TO service_role;

CREATE TABLE IF NOT EXISTS public.pedidos_oracao_aprovacoes_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  igreja_id uuid NOT NULL REFERENCES public.igrejas(id) ON DELETE CASCADE,
  pedido_id uuid NOT NULL,
  pedido_nome text NOT NULL,
  acao text NOT NULL CHECK (acao IN ('Aprovado', 'Rejeitado')),
  metodo text NOT NULL CHECK (metodo IN ('pin', 'admin')),
  ator_id uuid REFERENCES public.usuarios(id) ON DELETE SET NULL,
  ator_nome text NOT NULL,
  ator_email text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS pedidos_oracao_aprovacoes_log_church_created_idx
  ON public.pedidos_oracao_aprovacoes_log (igreja_id, created_at DESC);

ALTER TABLE public.pedidos_oracao_aprovacoes_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.pedidos_oracao_aprovacoes_log FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.pedidos_oracao_aprovacoes_log TO service_role;

CREATE OR REPLACE FUNCTION public.record_prayer_pin_failure(
  p_usuario_id uuid,
  p_igreja_id uuid
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
BEGIN
  UPDATE public.pedidos_oracao_pins AS pin
  SET
    tentativas_falhas = CASE
      WHEN pin.bloqueado_ate IS NOT NULL AND pin.bloqueado_ate <= pg_catalog.now() THEN 1
      ELSE pin.tentativas_falhas + 1
    END,
    bloqueado_ate = CASE
      WHEN pin.bloqueado_ate > pg_catalog.now() THEN pin.bloqueado_ate
      WHEN (
        CASE
          WHEN pin.bloqueado_ate IS NOT NULL AND pin.bloqueado_ate <= pg_catalog.now() THEN 1
          ELSE pin.tentativas_falhas + 1
        END
      ) >= 5 THEN pg_catalog.now() + interval '15 minutes'
      ELSE NULL
    END,
    updated_at = pg_catalog.now()
  WHERE pin.usuario_id = p_usuario_id
    AND pin.igreja_id = p_igreja_id;
END;
$function$;

CREATE OR REPLACE FUNCTION public.finalize_prayer_request(
  p_pedido_id uuid,
  p_igreja_id uuid,
  p_ator_id uuid,
  p_acao text,
  p_metodo text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
DECLARE
  v_ator record;
  v_pedido_nome text;
BEGIN
  IF p_acao NOT IN ('Aprovado', 'Rejeitado') THEN
    RAISE EXCEPTION 'Ação de aprovação inválida.' USING ERRCODE = '22023';
  END IF;
  IF p_metodo NOT IN ('pin', 'admin') THEN
    RAISE EXCEPTION 'Método de aprovação inválido.' USING ERRCODE = '22023';
  END IF;

  SELECT usuario.igreja_id, usuario.grupo_id, usuario.role, usuario.nome, usuario.email
  INTO v_ator
  FROM public.usuarios AS usuario
  WHERE usuario.id = p_ator_id;

  IF v_ator.igreja_id IS DISTINCT FROM p_igreja_id THEN
    RAISE EXCEPTION 'Usuário não pertence à igreja do pedido.' USING ERRCODE = '42501';
  END IF;

  IF v_ator.role = 'admin' THEN
    IF p_metodo <> 'admin' THEN
      RAISE EXCEPTION 'Administração deve usar aprovação administrativa.' USING ERRCODE = '42501';
    END IF;
  ELSE
    IF p_metodo <> 'pin' OR NOT EXISTS (
      SELECT 1
      FROM public.grupos_permissoes AS permissao
      WHERE permissao.grupo_id = v_ator.grupo_id
        AND permissao.modulo = 'monitor-oracoes'
        AND permissao.acao = 'aprovar'
    ) THEN
      RAISE EXCEPTION 'Usuário não tem autorização para aprovar orações.' USING ERRCODE = '42501';
    END IF;

    IF NOT EXISTS (
      SELECT 1
      FROM public.pedidos_oracao_pins AS pin
      WHERE pin.usuario_id = p_ator_id
        AND pin.igreja_id = p_igreja_id
        AND (pin.bloqueado_ate IS NULL OR pin.bloqueado_ate <= pg_catalog.now())
    ) THEN
      RAISE EXCEPTION 'PIN não configurado ou temporariamente bloqueado.' USING ERRCODE = '42501';
    END IF;
  END IF;

  UPDATE public.pedidos_oracao AS pedido
  SET status = p_acao
  WHERE pedido.id = p_pedido_id
    AND pedido.igreja_id = p_igreja_id
    AND pedido.status = 'Pendente'
  RETURNING pedido.nome_solicitante INTO v_pedido_nome;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Pedido não encontrado ou já processado.' USING ERRCODE = 'P0002';
  END IF;

  IF p_metodo = 'pin' THEN
    UPDATE public.pedidos_oracao_pins AS pin
    SET tentativas_falhas = 0, bloqueado_ate = NULL, updated_at = pg_catalog.now()
    WHERE pin.usuario_id = p_ator_id
      AND pin.igreja_id = p_igreja_id;
  END IF;

  INSERT INTO public.pedidos_oracao_aprovacoes_log (
    igreja_id, pedido_id, pedido_nome, acao, metodo, ator_id, ator_nome, ator_email
  ) VALUES (
    p_igreja_id,
    p_pedido_id,
    v_pedido_nome,
    p_acao,
    p_metodo,
    p_ator_id,
    COALESCE(NULLIF(btrim(v_ator.nome), ''), 'Usuário'),
    v_ator.email
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.record_prayer_pin_failure(uuid, uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.record_prayer_pin_failure(uuid, uuid) TO service_role;
REVOKE ALL ON FUNCTION public.finalize_prayer_request(uuid, uuid, uuid, text, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.finalize_prayer_request(uuid, uuid, uuid, text, text) TO service_role;

CREATE OR REPLACE FUNCTION public.prevent_unverified_prayer_approval()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $function$
BEGIN
  IF COALESCE(pg_catalog.current_setting('request.jwt.claim.role', true), '') <> 'service_role' THEN
    IF TG_OP = 'INSERT' AND NEW.status IN ('Aprovado', 'Rejeitado') THEN
      RAISE EXCEPTION 'A decisão deve ser feita pelo fluxo autenticado de orações.'
        USING ERRCODE = '42501';
    ELSIF TG_OP = 'UPDATE'
      AND NEW.status IS DISTINCT FROM OLD.status
      AND (NEW.status IN ('Aprovado', 'Rejeitado') OR OLD.status IN ('Aprovado', 'Rejeitado'))
    THEN
      RAISE EXCEPTION 'A decisão deve ser feita pelo fluxo autenticado de orações.'
        USING ERRCODE = '42501';
    END IF;
  END IF;

  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS prevent_unverified_prayer_approval ON public.pedidos_oracao;
CREATE TRIGGER prevent_unverified_prayer_approval
BEFORE INSERT OR UPDATE OF status ON public.pedidos_oracao
FOR EACH ROW
EXECUTE FUNCTION public.prevent_unverified_prayer_approval();

