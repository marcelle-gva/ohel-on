DECLARE
  v_policy record;
BEGIN
  FOR v_policy IN
    SELECT policy.polname
    FROM pg_catalog.pg_policy AS policy
    WHERE policy.polrelid = 'public.pedidos_oracao'::regclass
  LOOP
    EXECUTE pg_catalog.format(
      'DROP POLICY IF EXISTS %I ON public.pedidos_oracao',
      v_policy.polname
    );
  END LOOP;
END;
$policies$;

CREATE POLICY pedidos_oracao_select_church
ON public.pedidos_oracao FOR SELECT TO authenticated
USING (
  igreja_id = (
    SELECT usuario.igreja_id
    FROM public.usuarios AS usuario
    WHERE usuario.id = auth.uid()
  )
  AND (
    public.has_church_module_permission(igreja_id, 'oracoes', ARRAY['ler']::text[])
    OR public.has_church_module_permission(igreja_id, 'monitor-oracoes', ARRAY['aprovar']::text[])
    OR (status = 'Aprovado' AND visibilidade = 'Público')
  )
);

CREATE POLICY pedidos_oracao_insert_public_pending
ON public.pedidos_oracao FOR INSERT TO anon
WITH CHECK (
  status = 'Pendente'
  AND igreja_id IS NOT NULL
  AND EXISTS (SELECT 1 FROM public.igrejas AS igreja WHERE igreja.id = igreja_id)
);

CREATE POLICY pedidos_oracao_insert_public_pending_authenticated
ON public.pedidos_oracao FOR INSERT TO authenticated
WITH CHECK (
  status = 'Pendente'
  AND igreja_id IS NOT NULL
  AND EXISTS (SELECT 1 FROM public.igrejas AS igreja WHERE igreja.id = igreja_id)
);

CREATE POLICY pedidos_oracao_insert_church
ON public.pedidos_oracao FOR INSERT TO authenticated
WITH CHECK (
  status <> 'Aprovado'
  AND public.has_church_module_permission(igreja_id, 'oracoes', ARRAY['criar']::text[])
);

CREATE POLICY pedidos_oracao_update_church
ON public.pedidos_oracao FOR UPDATE TO authenticated
USING (public.has_church_module_permission(igreja_id, 'oracoes', ARRAY['editar']::text[]))
WITH CHECK (public.has_church_module_permission(igreja_id, 'oracoes', ARRAY['editar']::text[]));

CREATE POLICY pedidos_oracao_delete_church
ON public.pedidos_oracao FOR DELETE TO authenticated
USING (public.has_church_module_permission(igreja_id, 'oracoes', ARRAY['excluir']::text[]));
